package manager

import (
	"crypto/sha256"
	"fmt"
	"strings"
)

type Rendered struct {
	Text          string
	Env           []string
	Secrets       []string
	SecretDigest  string
	Digest        string
	MonitorReason string
}

// quote encodes a TOML 1.0 basic string. It escapes braces because frp
// expands Go templates before TOML parsing; TOML restores the original value.
// Unlike JSON, TOML forbids a literal DEL (U+007F).
func quote(s string) string {
	var b strings.Builder
	b.Grow(len(s) + 2)
	b.WriteByte('"')
	const hex = "0123456789ABCDEF"
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '{':
			b.WriteString(`\u007B`)
		case '}':
			b.WriteString(`\u007D`)
		case '\b':
			b.WriteString(`\b`)
		case '\t':
			b.WriteString(`\t`)
		case '\n':
			b.WriteString(`\n`)
		case '\f':
			b.WriteString(`\f`)
		case '\r':
			b.WriteString(`\r`)
		default:
			if r < 0x20 || r == 0x7f {
				b.WriteString(`\u00`)
				b.WriteByte(hex[r>>4])
				b.WriteByte(hex[r&15])
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

// frp through v0.61 uses html/template, while newer versions use
// text/template. Encode HTML-sensitive characters as TOML escapes so both
// engines preserve the exact credential bytes. Quotes remain in the config.
func templateCredential(s string) string {
	q := quote(s)
	q = q[1 : len(q)-1]
	r := strings.NewReplacer(`\"`, `\u0022`, "'", `\u0027`, "&", `\u0026`, "<", `\u003C`, ">", `\u003E`)
	return r.Replace(q)
}

// renderInstance writes the common connection settings for runtime and export.
func renderInstance(b *strings.Builder, i Instance) error {
	fmt.Fprintln(b, "# Generated by KurumiFRP. Drafts are not automatically applied.")
	fmt.Fprintln(b, "log.to = \"console\"\nlog.level = \"info\"\nlog.disablePrintColor = true")
	if i.Kind == "frps" {
		fmt.Fprintf(b, "bindAddr = %s\nbindPort = %d\ntransport.tls.force = %t\n", quote(i.Host), i.Port, !i.ServerAllowPlaintext)
		if i.HTTPPort > 0 {
			fmt.Fprintf(b, "vhostHTTPPort = %d\n", i.HTTPPort)
		}
		if i.HTTPSPort > 0 {
			fmt.Fprintf(b, "vhostHTTPSPort = %d\n", i.HTTPSPort)
		}
	} else {
		fmt.Fprintf(b, "serverAddr = %s\nserverPort = %d\nloginFailExit = %t\ntransport.tls.enable = %t\n", quote(i.Host), i.Port, i.LoginFailExit, !i.ClientTLSDisabled)
	}
	return renderProtocolInstance(b, i)
}

func (s *Store) render(id string, preview bool) (Rendered, error) {
	i, ok := s.DB.State.Instance(id)
	if !ok {
		return Rendered{}, fmt.Errorf("实例不存在")
	}
	r := Rendered{}
	var b strings.Builder
	secret := func(text, key string) (string, error) {
		p, e := s.decrypt(text)
		if e != nil {
			return "", e
		}
		if preview {
			return quote("<redacted>"), nil
		}
		// The template is expanded once; the environment contains TOML-safe
		// contents and the surrounding literal quotes remain in the file.
		r.Env = append(r.Env, key+"="+templateCredential(p))
		r.Secrets = append(r.Secrets, p)
		return "\"{{ .Envs." + key + " }}\"", nil
	}
	if err := renderInstance(&b, i); err != nil {
		return r, err
	}
	policy, err := parseControlAccess(i.ServerAccessMode, i.ServerAccessList)
	if err != nil {
		return r, err
	}
	if policy != nil {
		// A comment makes the policy visible in diffs without inventing an frp
		// TOML field. A standalone frps ignores it; only our embedded runtime enforces it.
		fmt.Fprintf(&b, "# KurumiFRP control-entry policy (embedded only): %s\n", policy.summary(i.ServerAccessMode))
	}
	v, e := secret(i.Token, "KURUMI_AUTH_TOML")
	if e != nil {
		return r, e
	}
	fmt.Fprintf(&b, "auth.method = \"token\"\nauth.token = %s\n", v)
	for _, t := range s.DB.State.Tunnels {
		if t.InstanceID != id || !t.Enabled {
			continue
		}
		if err := renderProtocolTunnel(&b, t, secret); err != nil {
			return r, err
		}
	}
	r.Text = b.String()
	r.SecretDigest = fmt.Sprintf("%x", sha256.Sum256([]byte(strings.Join(r.Env, "\x00"))))
	r.Digest = fmt.Sprintf("%x", sha256.Sum256([]byte(r.Text+strings.Join(r.Env, "\x00"))))
	return r, nil
}
