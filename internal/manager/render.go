func extractRangePairArgs(line string) (string, string) {
	idx := strings.Index(line, "parseNumberRangePair")
	if idx < 0 {
		return "", ""
	}
	rest := line[idx+len("parseNumberRangePair"):]
	var quoted []string
	for len(rest) > 0 {
		q1 := strings.IndexByte(rest, '"')
		if q1 < 0 {
			break
		}
		rest = rest[q1+1:]
		q2 := strings.IndexByte(rest, '"')
		if q2 < 0 {
			break
		}
		quoted = append(quoted, rest[:q2])
		rest = rest[q2+1:]
		if len(quoted) >= 2 {
			break
		}
	}
	if len(quoted) >= 2 {
		return quoted[0], quoted[1]
	}
	return "", ""
}

// tomlQuote strictly encodes a string literal according to the TOML v1.0 specification.
func tomlQuote(s string) string {
	var b strings.Builder
	b.Grow(len(s) + 2)
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\b':
			b.WriteString(`\b`)
		case '\t':
			b.WriteString(`\t`)
		case '\n':
			b.WriteString(`\n`)
		case '\f':
			b.WriteString(`\f`)
		case '\r':
			b.WriteString(`\r`)
		default:
			if r < 0x20 || r == 0x7f {
				fmt.Fprintf(&b, `\u%04X`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

// tomlInnerEscape escapes TOML special characters without outer quotes so os.Getenv expands cleanly inside "{{ .Envs.KEY }}".
func tomlInnerEscape(s string) string {
	q := tomlQuote(s)
	if len(q) >= 2 && q[0] == '"' && q[len(q)-1] == '"' {
		return q[1 : len(q)-1]
	}
	return s
}

func tomlStringArray(items []string) string {
	quoted := make([]string, 0, len(items))
	for _, it := range items {
		quoted = append(quoted, tomlQuote(it))
	}
	return "[" + strings.Join(quoted, ", ") + "]"
}

func cleanStringSlice(in []string) []string {
	var out []string
	for _, s := range in {
		if t := strings.TrimSpace(s); t != "" {
			out = append(out, t)
		}
	}
	return out
}

// ValidateAllowPortsSpec strictly validates server port whitelists (fail-closed against full-width commas, typos, or reversed ranges).
func ValidateAllowPortsSpec(spec string) ([][2]int, error) {
	trimmed := strings.TrimSpace(spec)
	if trimmed == "" {
		return nil, nil
	}
	if strings.ContainsAny(trimmed, "，；、") {
		return nil, errors.New("allowPorts 端口白名单包含中文全角标点（如“，”），请改用英文半角逗号分隔（如 2000-3000,4000）")
	}
	var out [][2]int
	for _, rawPart := range strings.Split(trimmed, ",") {
		part := strings.TrimSpace(rawPart)
		if part == "" {
			return nil, fmt.Errorf("allowPorts 端口白名单存在空片段: %q", trimmed)
		}
		if idx := strings.IndexByte(part, '-'); idx >= 0 {
			if idx == 0 || idx == len(part)-1 {
				return nil, fmt.Errorf("allowPorts 端口范围格式无效: %q", part)
			}
			a, err1 := strconv.Atoi(strings.TrimSpace(part[:idx]))
			b, err2 := strconv.Atoi(strings.TrimSpace(part[idx+1:]))
			if err1 != nil || err2 != nil || a <= 0 || b > 65535 || b < a {
				return nil, fmt.Errorf("allowPorts 端口范围 %q 不合法（需满足 1 <= 起始 <= 结束 <= 65535）", part)
			}
			out = append(out, [2]int{a, b})
		} else {
			p, err := strconv.Atoi(part)
			if err != nil || p <= 0 || p > 65535 {
				return nil, fmt.Errorf("allowPorts 端口号 %q 不合法（需在 1~65535 之间）", part)
			}
			out = append(out, [2]int{p, p})
		}
	}
	return out, nil
}

func parseAllowPortsSpec(spec string) [][2]int {
	ranges, err := ValidateAllowPortsSpec(spec)
	if err != nil {
		return nil
	}
	return ranges
}

// foldMultilineTOMLLines joins multiline bracketed TOML arrays `[ ... ]` while respecting single/double quotes and inline comments.
func foldMultilineTOMLLines(rawLines []string) ([]string, error) {
	var out []string
	var buf strings.Builder
	bracketDepth := 0

	scanLine := func(s string) (int, byte, error) {
		var quote byte
		escaped := false
		delta := 0
		for i := 0; i < len(s); i++ {
			c := s[i]
			if quote == '"' {
				if escaped {
					escaped = false
					continue
				}
				if c == '\\' {
					escaped = true
					continue
				}
				if c == '"' {
					quote = 0
				}
				continue
			}
			if quote == '\'' {
				if c == '\'' {
					quote = 0
				}
				continue
			}
			if c == '#' {
				break
			}
			if c == '"' || c == '\'' {
				quote = c
				continue
			}
			if c == '[' {
				delta++
			} else if c == ']' {
				delta--
			}
		}
		return delta, quote, nil
	}

	for idx, line := range rawLines {
		cleaned := stripTOMLInlineComment(line)
		trimmed := strings.TrimSpace(cleaned)
		if bracketDepth == 0 {
			if trimmed == "" || (strings.HasPrefix(trimmed, "[") && strings.HasSuffix(trimmed, "]") && !strings.Contains(trimmed, "=")) {
				out = append(out, trimmed)
				continue
			}
		}
		delta, unclosedQuote, _ := scanLine(cleaned)
		if unclosedQuote != 0 {
			return nil, fmt.Errorf("TOML 第 %d 行存在未闭合的字符串引号", idx+1)
		}
		if bracketDepth > 0 || delta > 0 {
			if buf.Len() > 0 {
				buf.WriteByte(' ')
				buf.WriteString(strings.TrimSpace(cleaned))
			} else {
				buf.WriteString(cleaned)
			}
			bracketDepth += delta
			if bracketDepth < 0 {
				return nil, fmt.Errorf("TOML 第 %d 行存在多余的右方括号 ']'", idx+1)
			}
			if bracketDepth == 0 {
				out = append(out, buf.String())
				buf.Reset()
			}
			continue
		}
		out = append(out, line)
	}
	if bracketDepth != 0 {
		return nil, errors.New("TOML 存在未闭合的多行数组 '['")
	}
	return out, nil
}

func stripTOMLInlineComment(s string) string {
	var quote byte
	escaped := false
	for i := 0; i < len(s); i++ {
		c := s[i]
		if quote == '"' {
			if escaped {
				escaped = false
				continue
			}
			if c == '\\' {
				escaped = true
				continue
			}
			if c == '"' {
				quote = 0
			}
			continue
		}
		if quote == '\'' {
			if c == '\'' {
				quote = 0
			}
			continue
		}
		if c == '"' || c == '\'' {
			quote = c
			continue
		}
		if c == '#' {
			return strings.TrimRight(s[:i], " \t")
		}
	}
	return s
}

func splitTOMLKeyVal(line string) (string, string, bool) {
	var quote byte
	escaped := false
	eqIdx := -1
	for i := 0; i < len(line); i++ {
		c := line[i]
		if quote == '"' {
			if escaped {
				escaped = false
				continue
			}
			if c == '\\' {
				escaped = true
				continue
			}
			if c == '"' {
				quote = 0
			}
			continue
		}
		if quote == '\'' {
			if c == '\'' {
				quote = 0
			}
			continue
		}
		if c == '"' || c == '\'' {
			quote = c
			continue
		}
		if c == '=' {
			eqIdx = i
			break
		}
	}
	if eqIdx <= 0 {
		return "", "", false
	}
	key := strings.TrimSpace(line[:eqIdx])
	val := strings.TrimSpace(stripTOMLInlineComment(line[eqIdx+1:]))
	return key, val, true
}

func unquoteTOML(v string) string {
	v = strings.TrimSpace(v)
	if len(v) >= 2 && ((v[0] == '"' && v[len(v)-1] == '"') || (v[0] == '\'' && v[len(v)-1] == '\'')) {
		if v[0] == '"' {
			if u, err := strconv.Unquote(v); err == nil {
				return u
			}
		}
		return v[1 : len(v)-1]
	}
	return v
}

func parseTOMLStringArray(v string) []string {
	v = strings.TrimSpace(v)
	v = strings.TrimPrefix(v, "[")
	v = strings.TrimSuffix(v, "]")
	var out []string
	var cur strings.Builder
	var quote byte
	escaped := false
	flush := func() {
		u := strings.TrimSpace(unquoteTOML(cur.String()))
		if u != "" {
			out = append(out, u)
		}
		cur.Reset()
	}
	for i := 0; i < len(v); i++ {
		c := v[i]
		if quote == '"' {
			cur.WriteByte(c)
			if escaped {
				escaped = false
				continue
			}
			if c == '\\' {
				escaped = true
				continue
			}
			if c == '"' {
				quote = 0
			}
			continue
		}
		if quote == '\'' {
			cur.WriteByte(c)
			if c == '\'' {
				quote = 0
			}
			continue
		}
		if c == '"' || c == '\'' {
			quote = c
			cur.WriteByte(c)
			continue
		}
		if c == ',' {
			flush()
			continue
		}
		cur.WriteByte(c)
	}
	if cur.Len() > 0 {
		flush()
	}
	return out
}
