package manager

import (
	"crypto/sha256"
	"fmt"
	"strings"
)

type Rendered struct {
	Text         string
	Env          []string
	Secrets      []string
	SecretDigest string
	Digest       string
}

// quote encodes a TOML 1.0 basic string. Unlike JSON, TOML forbids a
// literal DEL (U+007F), so sharing encoding/json's string encoder is unsafe.
func quote(s string) string {
	var b strings.Builder
	b.Grow(len(s) + 2)
	b.WriteByte('"')
	const hex = "0123456789ABCDEF"
	for _, r := range s {
		switch r {
		case '\\':
			b.WriteString(`\\`)
		case '"':
			b.WriteString(`\"`)
		case '\b':
			b.WriteString(`\b`)
		case '\t':
			b.WriteString(`\t`)
		case '\n':
			b.WriteString(`\n`)
		case '\f':
			b.WriteString(`\f`)
		case '\r':
			b.WriteString(`\r`)
		default:
			if r < 0x20 || r == 0x7f {
				b.WriteString(`\u00`)
				b.WriteByte(hex[r>>4])
				b.WriteByte(hex[r&15])
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

func (s *Store) render(id string, preview bool) (Rendered, error) {
	i, ok := s.DB.State.Instance(id)
	if !ok {
		return Rendered{}, fmt.Errorf("实例不存在")
	}
	r := Rendered{}
	var b strings.Builder
	secret := func(text, key string) (string, error) {
		p, e := s.decrypt(text)
		if e != nil {
			return "", e
		}
		if preview {
			return quote("<redacted>"), nil
		}
		// The template is deliberately UNQUOTED: its environment value is a
		// complete TOML literal, not a shell argument or an unescaped password.
		// frp expands it once; do not strip these quotes or add template quotes.
		r.Env = append(r.Env, key+"="+quote(p))
		r.Secrets = append(r.Secrets, p)
		return "{{ .Envs." + key + " }}", nil
	}
	fmt.Fprintln(&b, "# Generated by KurumiFRP. Drafts are not automatically applied.")
	fmt.Fprintln(&b, "log.to = \"console\"\nlog.level = \"info\"\nlog.disablePrintColor = true")
	if i.Kind == "frps" {
		fmt.Fprintf(&b, "bindAddr = %s\nbindPort = %d\ntransport.tls.force = true\n", quote(i.Host), i.Port)
		if i.HTTPPort > 0 {
			fmt.Fprintf(&b, "vhostHTTPPort = %d\n", i.HTTPPort)
		}
		if i.HTTPSPort > 0 {
			fmt.Fprintf(&b, "vhostHTTPSPort = %d\n", i.HTTPSPort)
		}
	} else {
		fmt.Fprintf(&b, "serverAddr = %s\nserverPort = %d\nloginFailExit = false\ntransport.tls.enable = true\n", quote(i.Host), i.Port)
	}
	v, e := secret(i.Token, "KURUMI_AUTH_TOML")
	if e != nil {
		return r, e
	}
	fmt.Fprintf(&b, "auth.method = \"token\"\nauth.token = %s\n", v)
	for _, t := range s.DB.State.Tunnels {
		if t.InstanceID != id || !t.Enabled {
			continue
		}
		if t.Type == "stcp-visitor" {
			fmt.Fprintf(&b, "\n[[visitors]]\nname = %s\ntype = \"stcp\"\nserverName = %s\nbindAddr = %s\nbindPort = %d\n", quote(t.Name), quote(t.ServerName), quote(t.LocalHost), t.LocalPort)
		} else {
			fmt.Fprintf(&b, "\n[[proxies]]\nname = %s\ntype = %s\nlocalIP = %s\nlocalPort = %d\n", quote(t.Name), quote(t.Type), quote(t.LocalHost), t.LocalPort)
			if t.Type == "tcp" || t.Type == "udp" {
				fmt.Fprintf(&b, "remotePort = %d\n", t.RemotePort)
			}
			if t.Type == "http" || t.Type == "https" {
				a := []string{}
				for _, d := range t.Domains {
					a = append(a, quote(d))
				}
				fmt.Fprintf(&b, "customDomains = [%s]\n", strings.Join(a, ", "))
			}
			if t.BandwidthKB > 0 {
				fmt.Fprintf(&b, "transport.bandwidthLimit = \"%dKB\"\ntransport.bandwidthLimitMode = \"client\"\n", t.BandwidthKB)
			}
		}
		if t.Type == "stcp" || t.Type == "stcp-visitor" {
			v, e := secret(t.Secret, "KURUMI_SECRET_"+t.ID)
			if e != nil {
				return r, e
			}
			fmt.Fprintf(&b, "secretKey = %s\n", v)
		}
	}
	r.Text = b.String()
	r.SecretDigest = fmt.Sprintf("%x", sha256.Sum256([]byte(strings.Join(r.Env, "\x00"))))
	r.Digest = fmt.Sprintf("%x", sha256.Sum256([]byte(r.Text+strings.Join(r.Env, "\x00"))))
	return r, nil
}
